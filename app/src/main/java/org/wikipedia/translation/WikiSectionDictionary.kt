    private val dictionaries = mapOf("ru" to RU)

    /** Возвращает перевод заголовка из словаря, или null если не найден. */
    fun translate(title: String, targetLang: String): String? {
        val dict = dictionaries[targetLang] ?: return null
        return dict[title] ?: dict[title.trim()]
    }

    /**
     * Разбивает список заголовков на два: переведённые из словаря и те, что нужно
     * отправить во внешний сервис.
     */
    fun partition(titles: List<String>, targetLang: String): Pair<Map<String, String>, List<String>> {
        val found = mutableMapOf<String, String>()
        val missing = mutableListOf<String>()
        for (title in titles) {
            val t = translate(title, targetLang)
            if (t != null) found[title] = t else missing.add(title)
        }
        return found to missing
    }
